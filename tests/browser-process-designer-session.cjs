const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require('playwright')

async function run() {
  const root = path.resolve(__dirname, '..')
  const { createAtlasServer } = await import(pathToFileURL(path.join(root, 'tools/serve.mjs')).href)
  const server = await createAtlasServer({rootDir:root,getApiKey:()=>undefined,transport:()=>{throw Error('Unexpected inference request')}})
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve))
  let browser
  const errors=[]
  const output=path.join(root,'local-knowledge/retests/process-session-lifecycle',new Date().toISOString().replace(/[:.]/g,'-'))
  await fs.mkdir(output,{recursive:true})
  const lifecycle={method:'Public application controls and downloaded JSON. No inference requests.',findings:[]}
  try {
    browser=await chromium.launch({channel:'chrome',headless:true})
    const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true})
    page.on('pageerror',error=>errors.push(error.message))
    await page.route('**/designer-session-trial',route=>route.fulfill({contentType:'text/html',body:`<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Process session trial</title><style>body{margin:16px;--bg:#f4f7fb;--paper:#fff;--soft:#eef2f7;--ink:#1c2739;--muted:#56647a;--line:#bdc8d7}button{min-height:44px;margin:4px}input{padding:12px}</style></head><body><nav aria-label="Workspace"><button id="brief">Brief</button><button id="workflow">Workflow</button><button id="knowledge">Knowledge map</button></nav><section id="brief-view" hidden><label>Outcome <input id="outcome"></label></section><section id="knowledge-view" hidden><h1>Knowledge map</h1></section><div id="workflow-host"></div><button id="change-process">Accept another process edit</button><button id="download">Download current project</button><script type="module">
      import {createRecipe,compile} from '/factory/core.mjs';
      import {createProcessDraft,applyProcessEdit} from '/factory/process-editor.mjs';
      import {createProcessDesigner} from '/factory/process-designer.mjs';
      let config=applyProcessEdit(createRecipe(),'team-review',createProcessDraft({id:'team-review',name:'Team review',patternId:'review-gate'})).config;
      const apply=next=>{config=next;window.applied=(window.applied||0)+1};
      apply.preview=next=>{const before=new Map(compile(config).files.map(file=>[file.path,file.content]));return compile(next).files.filter(file=>file.content!==before.get(file.path)).map(file=>file.path)};
      const designer=createProcessDesigner({getConfig:()=>config,onApply:apply});
      designer.mount(document.querySelector('#workflow-host'));designer.open('team-review');
      for(const view of ['brief','workflow','knowledge'])document.querySelector('#'+view).onclick=()=>{document.querySelector('#brief-view').hidden=view!=='brief';document.querySelector('#knowledge-view').hidden=view!=='knowledge';document.querySelector('#workflow-host').hidden=view!=='workflow';if(view==='workflow')designer.resume();else designer.suspend();};
      document.querySelector('#outcome').oninput=event=>{config.project.purpose=event.target.value;designer.syncConfig()};
      let externalChange=0;
      document.querySelector('#change-process').onclick=()=>{externalChange+=1;config.workflowModel.processes.find(process=>process.id===designer.getContext().processId).steps[0].action='Newer accepted process action '+externalChange;designer.syncConfig()};
      document.querySelector('#download').onclick=()=>{const link=document.createElement('a');link.href=URL.createObjectURL(new Blob([JSON.stringify(config)],{type:'application/json'}));link.download='process-session.json';link.click();setTimeout(()=>URL.revokeObjectURL(link.href),1000)};
    </script></body></html>`}))
    await page.goto(`http://127.0.0.1:${server.address().port}/designer-session-trial`)
    const designer=page.locator('#process-designer')
    assert.equal(await designer.locator('[data-pe-detail="settings"]').getAttribute('open'),null)
    assert.equal(await designer.locator('#pe-title').innerText(),'Team review')
    await designer.locator('[data-pe-bind="steps.0.action"]').fill('My pending process action')
    const inspector=designer.locator('.pe-inspector')
    await inspector.hover()
    await page.mouse.wheel(0,300)
    await page.waitForFunction(()=>document.querySelector('.pe-inspector').scrollTop>0)
    const inspectorScroll=await inspector.evaluate(element=>element.scrollTop)
    await page.locator('#brief').click()
    assert.equal(await designer.isVisible(),false)
    await page.locator('#outcome').fill('A revised outcome from Brief')
    await page.locator('#knowledge').click()
    assert.equal(await page.locator('#knowledge-view').isVisible(),true)
    await page.locator('#workflow').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(),'My pending process action')
    assert.ok(Math.abs(await inspector.evaluate(element=>element.scrollTop)-inspectorScroll)<3,'Inspector scroll survives navigation and unrelated Brief edit')
    await designer.locator('[data-pe-detail="settings"] summary').click()
    await page.locator('#knowledge').click()
    await page.locator('#workflow').click()
    assert.equal(await designer.locator('[data-pe-detail="settings"]').getAttribute('open'),'')
    await designer.locator('[data-pe-detail="settings"] summary').click()
    assert.equal(await page.locator('dialog[open]').count(),0)
    await designer.locator('[data-pe-action="review"]').click()
    assert.match(await designer.innerText(),/other project changes are kept/)
    await designer.locator('[data-pe-action="apply"]').click()
    assert.equal(await designer.isVisible(),true)
    assert.equal(await page.evaluate(()=>window.applied),1)

    await designer.locator('[data-pe-bind="steps.0.action"]').fill('My second pending action')
    await designer.locator('[data-pe-action="review"]').click()
    await page.locator('#change-process').click()
    assert.match(await designer.innerText(),/This process changed elsewhere/)
    assert.equal(await designer.locator('[data-pe-action="apply"]').count(),0)
    assert.equal(await designer.locator('[data-pe-action="review"]').isDisabled(),true)
    await designer.locator('[data-pe-action="copy-draft"]').click()
    await designer.locator('[data-pe-action="apply"]').click()
    assert.equal(await page.evaluate(()=>window.applied),2)
    const downloadEvent=page.waitForEvent('download')
    await page.locator('#download').click()
    const download=await downloadEvent
    const project=JSON.parse(await fs.readFile(await download.path(),'utf8'))
    assert.equal(project.project.purpose,'A revised outcome from Brief')
    assert.equal(project.workflowModel.processes.find(process=>process.id==='team-review').steps[0].action,'Newer accepted process action 1')
    assert.equal(project.workflowModel.processes.find(process=>process.id==='team-review-copy').steps[0].action,'My second pending action')

    await designer.locator('[data-pe-bind="steps.0.action"]').fill('Edits I will explicitly discard')
    await designer.locator('[data-pe-action="list"]').click()
    await designer.locator('[data-pe-action="request-discard"]').click()
    await designer.locator('[data-pe-action="keep-editing"]').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(),'Edits I will explicitly discard')
    await designer.locator('[data-pe-action="request-discard"]').click()
    await designer.locator('[data-pe-action="discard"]').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(),'My second pending action')
    await designer.locator('[data-pe-bind="steps.0.action"]').fill('A design I will discard in favor of the current version')
    await page.locator('#change-process').click()
    await designer.locator('[data-pe-action="keep-current"]').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(),'Newer accepted process action 2')
    assert.equal(await page.evaluate(()=>window.applied),2)
    await designer.locator('[data-pe-bind="steps.0.action"]').fill('An explicitly reviewed replacement')
    await page.locator('#change-process').click()
    await designer.locator('[data-pe-action="review-over-current"]').click()
    assert.equal(await page.evaluate(()=>window.applied),2)
    await designer.locator('[data-pe-action="apply"]').click()
    assert.equal(await page.evaluate(()=>window.applied),3)
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(),'An explicitly reviewed replacement')
    for(const width of [1440,768,390,320]) {
      await page.setViewportSize({width,height:700})
      const overflow=await designer.evaluate(element=>{const edge=element.getBoundingClientRect().right;return [...element.querySelectorAll('*')].filter(child=>child.getBoundingClientRect().right>edge+2).slice(0,5).map(child=>({tag:child.tagName,cls:child.className,width:child.getBoundingClientRect().width,text:child.textContent.slice(0,50)}))});assert.equal(await designer.evaluate(element=>element.scrollWidth>element.clientWidth+2),false,`Inline process content fits ${width}px ${JSON.stringify(overflow)}`)
    }

    const app=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true})
    app.on('pageerror',error=>errors.push(error.message))
    await app.goto(`http://127.0.0.1:${server.address().port}/factory/#brief`)
    await app.locator('[data-start-process]').click()
    const appDesigner=app.locator('#process-designer')
    await appDesigner.locator('[data-pe-start="name"]').fill('Accepted process for history recovery')
    await appDesigner.locator('[data-pe-action="create"]').click()
    await appDesigner.locator('[data-pe-action="review"]').click()
    await appDesigner.locator('[data-pe-action="apply"]').click()
    await appDesigner.locator('[data-pe-bind="steps.0.action"]').fill('Pending action kept when Redo restores the accepted base')
    await app.locator('#undo').click()
    assert.equal(await appDesigner.locator('.pe-conflict').isVisible(),true)
    await app.locator('#redo').click()
    const staleConflict=await appDesigner.locator('.pe-conflict').isVisible()
    assert.equal(await appDesigner.locator('[data-pe-bind="steps.0.action"]').inputValue(),'Pending action kept when Redo restores the accepted base')
    lifecycle.findings.push({case:'Undo conflict then Redo to the original accepted base',staleConflict,pendingActionRetained:true})
    await app.screenshot({path:path.join(output,'redo-accepted-base.png')})
    // Recover through explicit controls even on an unfixed build, so both regressions are observed.
    if(staleConflict)await appDesigner.locator('[data-pe-action="keep-current"]').click()
    else {
      await appDesigner.locator('[data-pe-action="request-discard"]').click()
      await appDesigner.locator('[data-pe-action="discard"]').click()
    }
    await appDesigner.locator('[data-pe-action="overview"]').click()
    await app.locator('[data-pe-new]').click()
    await appDesigner.locator('[data-pe-start="name"]').fill('Named draft reviewed before switching')
    await appDesigner.locator('[data-pe-start="kind"]').selectOption('development')
    await appDesigner.locator('[data-pe-start="pattern"]').selectOption('review-gate')
    await appDesigner.locator('[data-pe-action="overview"]').click()
    await app.locator('[data-pe-open]').first().click()
    await appDesigner.locator('[data-pe-action="review-before-switch"]').click()
    const reviewVisible=await appDesigner.locator('.pe-review').isVisible()
    const reviewError=await appDesigner.locator('[role="alert"]').allTextContents()
    lifecycle.findings.push({case:'Review a named starting pattern before switching',reviewVisible,reviewError})
    await app.screenshot({path:path.join(output,'named-draft-review.png')})
    const failures=[]
    if(staleConflict)failures.push('Redo retained a stale process conflict after restoring its accepted base')
    if(!reviewVisible || reviewError.length)failures.push(`Named uncreated draft did not reach review: ${reviewError.join(' ')}`)
    assert.deepEqual(failures,[])
    assert.equal(await appDesigner.locator('#pe-title').innerText(),'Named draft reviewed before switching')
    assert.equal(await appDesigner.locator('[data-pe-action="apply"]').isEnabled(),true)
    await app.locator('#download-project').click()
    await app.locator('#download-accepted-only').check()
    await app.locator('.other-downloads summary').click()
    let [actualDownload]=await Promise.all([app.waitForEvent('download'),app.locator('[data-studio-action="download-json"]').click()])
    let jsonBytes=await fs.readFile(await actualDownload.path())
    const acceptedBeforeApply=JSON.parse(jsonBytes.toString('utf8'))
    assert.equal(acceptedBeforeApply.workflowModel.processes.length,1)
    assert.equal(acceptedBeforeApply.workflowModel.processes[0].name,'Accepted process for history recovery')
    await fs.writeFile(path.join(output,'accepted-before-switch-review.project.json'),jsonBytes)
    await appDesigner.locator('[data-pe-action="apply"]').click()
    assert.equal(await appDesigner.locator('#pe-title').innerText(),'Accepted process for history recovery')
    assert.equal(await appDesigner.locator('[data-pe-bind="steps.0.action"]').inputValue(),'')
    await app.locator('#download-project').click()
    if(await app.locator('.other-downloads').getAttribute('open')===null)await app.locator('.other-downloads summary').click()
    ;[actualDownload]=await Promise.all([app.waitForEvent('download'),app.locator('[data-studio-action="download-json"]').click()])
    jsonBytes=await fs.readFile(await actualDownload.path())
    const acceptedAfterApply=JSON.parse(jsonBytes.toString('utf8'))
    assert.equal(acceptedAfterApply.workflowModel.processes.length,2)
    const added=acceptedAfterApply.workflowModel.processes.find(process=>process.name==='Named draft reviewed before switching')
    assert.equal(added.kind,'development')
    assert.equal(added.pattern.id,'review-gate')
    await fs.writeFile(path.join(output,'accepted-after-switch-review.project.json'),jsonBytes)
    lifecycle.passed=true
    lifecycle.findings.push({case:'Switch review is buffered until explicit Apply',acceptedProcessCountBefore:1,acceptedProcessCountAfter:2,preservedNameKindAndPattern:true,switchedToRequestedAcceptedProcess:true})
    await app.close()
    assert.deepEqual(errors,[])
    console.log('Process session browser checks passed. Navigation retains edits, unrelated changes rebase, stale review is blocked, conflict copies preserve both accepted and pending designs, and downloaded JSON agrees.')
  }finally{
    await fs.writeFile(path.join(output,'report.json'),JSON.stringify({...lifecycle,errors},null,2))
    await browser?.close()
    await new Promise(resolve=>server.close(resolve))
    console.log(`Lifecycle evidence: ${output}`)
  }
}
run().catch(error=>{console.error(error);process.exitCode=1})
