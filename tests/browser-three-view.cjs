const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require('playwright')

async function run() {
  const root = path.resolve(__dirname, '..')
  const { createAtlasServer } = await import(pathToFileURL(path.join(root, 'tools/serve.mjs')).href)
  const { unzipTextFiles } = await import(pathToFileURL(path.join(root, 'factory/zip.mjs')).href)
  const output = path.join(root, 'local-knowledge/retests/three-view', new Date().toISOString().replace(/[:.]/g, '-'))
  await fs.mkdir(output, { recursive: true })
  const report = { method: 'Public browser controls, file-input imports and actual downloaded bytes with synthetic work. No application state injection or live inference.', limits: 'Browser simulation and screenshot review. No human study, real touch device, screen reader or production reliability claim.', checks: [], downloads: [], errors: [], providerCalls: 0 }
  const server = await createAtlasServer({ getApiKey: () => '', transport: async () => {report.providerCalls += 1; throw Error('Inference disabled')} })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const base = `http://127.0.0.1:${server.address().port}/factory/`
  let browser
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true })
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true, reducedMotion: 'reduce' })
    let page = await context.newPage()
    context.on('page', p => p.on('pageerror', error => report.errors.push(error.message)))
    page.on('pageerror', error => report.errors.push(error.message))
    page.setDefaultTimeout(10000)
    const main = async view => {await page.locator(`.main-navigation [data-main-view="${view}"]`).click()}
    const shot = async name => {
      await page.locator('#toast').waitFor({state:'hidden',timeout:10000})
      await page.screenshot({ path: path.join(output, `${name}.png`), fullPage: false })
    }
    const zip = async name => {
      const waiting = page.waitForEvent('download')
      await page.locator('[data-studio-action="download-output"]').click()
      const download = await waiting
      const filePath = path.join(output, `${name}.zip`)
      await download.saveAs(filePath)
      const bytes = await fs.readFile(filePath)
      const { files } = await unzipTextFiles(new Uint8Array(bytes))
      report.downloads.push({ name, bytes: bytes.length, paths: files.map(file => file.path) })
      return { filePath, files, project: JSON.parse(files.find(file => file.path === 'project.json').content) }
    }
    const open = async filePath => {
      await page.locator('#import-config').click()
      await page.locator('#import-file').setInputFiles(filePath)
      if (await page.locator('#confirm-dialog').isVisible()) await page.locator('#confirm-dialog [value="replace"]').click()
      await page.locator('#project-name').waitFor({ state: 'visible' })
    }
    const closeDownload = async () => {if(await page.locator('#download-dialog').isVisible()) await page.locator('[data-close-dialog="download-dialog"]').click()}
    await page.goto(base)
    assert.equal(await page.locator('.main-navigation [aria-current="page"]').innerText(), 'Brief')
    assert.equal(await page.locator('#studio-layout').isVisible(), false)
    await shot('brief-start-desktop')
    const wanted = 'Let customers save search filters and reopen the exact criteria.'
    await page.locator('#jev-brief').fill(wanted)
    await main('knowledge')
    const map = page.frameLocator('#knowledge-frame')
    await map.locator('#knowledge-back').waitFor({state:'visible'})
    await shot('knowledge-desktop')
    assert.equal(await page.locator('.studio-header').isVisible(), true)
    await main('brief')
    assert.equal(await page.locator('#jev-brief').inputValue(), wanted)
    await page.locator('[data-start-recipe="feature-delivery"]').click()
    await page.locator('#jev-create').click()
    await page.locator('#project-name').fill('Saved filters')
    assert.equal(await page.locator('#project-purpose').inputValue(), wanted)
    await page.locator('[data-field="workflow.answers.acceptance"]').fill('Given false, zero and empty criteria, saving and reopening preserves every value.')
    await shot('brief-project-desktop')
    await main('workflow')
    await shot('workflow-recipe-desktop')
    await page.locator('[data-select-stage="requirements"]').first().click()
    await page.locator('[data-field="workflow.notes.requirements"]').fill('Confirm acceptance with the product owner before implementation.')
    await page.locator('#download-project').click()
    await page.locator('[data-output-kind="blueprint"]').check()
    const blueprint = await zip('pm-blueprint')
    assert.ok(!blueprint.files.some(file => file.path.startsWith('.github/agents/')))
    assert.match(blueprint.files.find(file => file.path === 'templates/REQUIREMENTS.md').content, /false, zero and empty/)
    assert.match(blueprint.files.find(file => file.path === 'WORKFLOW.md').content, /product owner/)
    report.checks.push('A and B: an empty session keeps its description through Knowledge, creates a manual draft, and downloads a PM blueprint with literal acceptance and unresolved details.')
    await closeDownload()
    await main('brief')
    const revised = 'Let customers save and share search filters while preserving exact criteria.'
    await page.locator('#project-purpose').fill(revised)
    await page.locator('#brief-workspace [data-project-view="artifacts"]').click()
    await page.locator('[data-file="WORKFLOW.md"]').click()
    assert.match(await page.locator('#file-preview').innerText(), /save and share/)
    await page.locator('#download-project').click()
    await page.locator('[data-output-kind="pack"]').check()
    const full = await zip('engineer-pack')
    assert.equal(full.project.project.purpose, revised)
    assert.match(full.files.find(file => file.path === 'WORKFLOW.md').content, /product owner/)
    await closeDownload()
    const jsonPath = path.join(output, 'project.json')
    const htmlPath = path.join(output, 'PROJECT-ATLAS.html')
    await fs.writeFile(jsonPath, full.files.find(file => file.path === 'project.json').content)
    await fs.writeFile(htmlPath, full.files.find(file => file.path === 'PROJECT-ATLAS.html').content)
    for (const filePath of [full.filePath, jsonPath, htmlPath]) {
      page = await context.newPage()
      await page.goto(base)
      await open(filePath)
      await main('brief')
      assert.equal(await page.locator('#project-purpose').inputValue(), revised)
      await main('workflow')
      await page.locator('[data-select-stage="requirements"]').first().click()
      assert.equal(await page.locator('[data-field="workflow.notes.requirements"]').inputValue(), 'Confirm acceptance with the product owner before implementation.')
    }
    report.checks.push('C and H: exact accepted Brief and stage edits reach the full ZIP and reopen through ZIP, JSON and HTML controls.')
    page = await context.newPage()
    await page.goto(base)
    await page.locator('[data-start-process]').click()
    const designer = page.locator('#process-designer')
    await designer.locator('[data-pe-start="name"]').fill('Review a proposed result')
    await designer.locator('[data-pe-start="pattern"]').selectOption('bounded-correction')
    await designer.locator('[data-pe-action="create"]').click()
    await designer.locator('[data-pe-bind="steps.0.action"]').fill('Prepare a proposal using the supplied request and approved interfaces.')
    await main('knowledge')
    await main('brief')
    await page.locator('#project-name').fill('Proposal review')
    await page.locator('#project-purpose').fill('Keep a proposed result within the agreed scope before approval.')
    await main('workflow')
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(), 'Prepare a proposal using the supplied request and approved interfaces.')
    await page.locator('#download-project').click()
    assert.equal(await page.locator('#download-pending-note').isVisible(), true)
    await page.locator('#download-accepted-only').check()
    const pending = await zip('accepted-with-pending')
    assert.equal(pending.project.workflowModel.processes.filter(p => p.source === 'custom').length, 0)
    assert.match(pending.project.project.purpose, /agreed scope/)
    await closeDownload()
    await main('workflow')
    await designer.locator('[data-pe-action="review"]').click()
    await designer.locator('[data-pe-action="apply"]').click()
    await main('brief')
    assert.match(await page.locator('#project-purpose').inputValue(), /agreed scope/)
    await main('workflow')
    await designer.locator('[data-pe-bind="steps.0.action"]').fill('Pending change kept during practice adoption.')
    await main('knowledge')
    const currentFrame=page.frames().find(frame=>frame.url().includes('/atlas/'))
    await currentFrame.locator('#mobile-topics').click()
    await currentFrame.locator('#mobile-search').fill('Context')
    await currentFrame.locator('#mobile-nav [data-topic="context-selection"]').click()
    await currentFrame.getByRole('button', { name: 'Review for my workflow', exact: true }).click()
    await page.getByRole('button',{name:'Keep my workflow unchanged',exact:true}).click()
    await currentFrame.getByRole('button', { name: 'Review for my workflow', exact: true }).click()
    await page.locator('#apply-practice').click()
    await main('workflow')
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(), 'Pending change kept during practice adoption.')
    await page.locator('#undo').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(), 'Pending change kept during practice adoption.')
    await designer.locator('[data-pe-action="review"]').click()
    await designer.locator('[data-pe-action="apply"]').click()
    report.checks.push('D and E: pending process edits survive Knowledge, Brief and practice cancel/apply/Undo. An explicit accepted-only ZIP omits the pending design. Applying then preserves the newer Brief.')
    await designer.locator('[data-pe-bind="steps.0.action"]').fill('My separate design survives an accepted history conflict.')
    for(let count=0;count<8 && !(await designer.locator('.pe-conflict').isVisible());count++) await page.locator('#undo').click()
    assert.equal(await designer.locator('.pe-conflict').isVisible(),true)
    await designer.locator('[data-pe-action="copy-draft"]').click()
    assert.equal(await designer.locator('.pe-review').isVisible(),true)
    await designer.locator('[data-pe-action="apply"]').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.0.action"]').inputValue(),'My separate design survives an accepted history conflict.')
    report.checks.push('D conflict: Undo changing the same accepted process retains the pending design, and an explicit keep-both recovery can be reviewed and applied.')
    for(const width of [1440,768,390,320]) {
      await page.setViewportSize({width,height:width===320?568:1000})
      for(const theme of ['light','dark']) {
        if(await page.locator('html').getAttribute('data-theme')!==theme) await page.locator('#theme-toggle').click()
        for(const view of ['brief','workflow','knowledge']) {
          await main(view)
          if(view==='knowledge') await page.frameLocator('#knowledge-frame').locator('#knowledge-back').waitFor({state:'visible'})
          assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1), `${view} ${width} ${theme} overflows`)
          await shot(`${view}-${width}-${theme}`)
        }
      }
    }
    report.checks.push('Responsive views: all three destinations fit 1440, 768, 390 and 320 pixels in both themes, including a 320 by 568 viewport.')
    await page.setViewportSize({width:1440,height:1000})
    await main('knowledge')
    const finalMap = page.frameLocator('#knowledge-frame')
    await finalMap.locator('.mode-nav [data-mode="explore"]').click()
    await finalMap.locator('#overview-button').click()
    if (!await finalMap.locator('[data-view="3d"]').isDisabled()) await finalMap.locator('[data-view="3d"]').click()
    await page.waitForFunction(() => ['ready','fallback'].includes(document.querySelector('#knowledge-frame').contentDocument.body.dataset.graph))
    await shot('knowledge-map-overview-desktop')
    await page.setViewportSize({width:390,height:844})
    await shot('knowledge-map-390-dark')
    assert.equal(report.providerCalls,0)
    assert.deepEqual(report.errors,[])
    await fs.writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n')
    console.log(`Three-view UI journeys passed. ${report.checks.length} groups, ${report.downloads.length} actual ZIPs. Evidence: ${output}`)
  } catch(error) {
    report.failure=error.message
    await fs.writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n')
    throw error
  } finally {await browser?.close();await new Promise(resolve=>server.close(resolve))}
}
run().catch(error=>{console.error(error);process.exitCode=1})
