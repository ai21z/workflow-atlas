const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require('playwright')

async function run() {
  const root = path.resolve(__dirname, '..')
  const { createAtlasServer } = await import(pathToFileURL(path.join(root, 'tools/serve.mjs')).href)
  const { createRecipe, compileSelectedOutput } = await import(pathToFileURL(path.join(root, 'factory/core.mjs')).href)
  const { packageProject } = await import(pathToFileURL(path.join(root, 'factory/portable.mjs')).href)
  const { zipFiles, unzipTextFiles } = await import(pathToFileURL(path.join(root, 'factory/zip.mjs')).href)
  const output = path.join(root, 'local-knowledge/retests/output-transitions', new Date().toISOString().replace(/[:.]/g, '-'))
  await fs.mkdir(output, { recursive: true })
  const report = { method: 'Public UI on an isolated local server without credentials. Generated fixture ZIPs enter through the normal file chooser. Keyboard checks use keyboard events and DOM observations.', limits: 'Functional browser evidence, not human comprehension or assistive technology evidence.', checks: [], pageErrors: [] }
  const server = await createAtlasServer({ rootDir: root, getApiKey: () => undefined, transport: () => { throw new Error('Unexpected provider call') } })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  let browser, page
  const fresh = async (viewport = { width: 1440, height: 1000 }) => {
    if (page) await page.close()
    page = await browser.newPage({ viewport, acceptDownloads: true })
    page.setDefaultTimeout(5000)
    page.on('pageerror', error => report.pageErrors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.address().port}/factory/`)
    await page.locator('[data-start-recipe="bugfix"]').click()
    await page.locator('#brief-name').fill('Output transitions')
    await page.locator('#brief-purpose').fill('Keep false and zero in saved filters.')
    await page.locator('#brief-form button[type="submit"]').click()
  }
  const open = async () => { await page.locator('#download-project').click(); await page.locator('#download-dialog').waitFor({ state: 'visible' }) }
  const close = () => page.locator('[data-close-dialog="download-dialog"]').click()
  const skill = async () => { await open(); await page.locator('[data-output-kind="skill"]').check(); await page.locator('#output-skill').selectOption('bug-diagnosis'); await close() }
  const check = async (id, action) => {
    const record = { id, status: 'Not run' }
    report.checks.push(record)
    try { record.observation = await action(); record.status = 'Pass' }
    catch (error) { record.status = 'Fail'; record.error = error.stack || String(error); await page.screenshot({ path: path.join(output, `${id}.png`) }) }
    console.log(`${id}: ${record.status}`)
    await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2) + '\n')
  }
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true })
    await check('empty-stages-undo-redo', async () => {
      await fresh()
      await skill()
      for (const stage of ['bug-review', 'regression', 'bug-fix', 'diagnosis', 'reproduction']) {
        await page.locator(`[data-select-stage="${stage}"]`).first().click()
        await page.locator(`[data-stage="${stage}"]`).uncheck()
        await page.locator('#close-inspector').click()
      }
      await open()
      assert.equal(await page.locator('[data-output-kind="skill"]').isChecked(), true)
      assert.equal(await page.locator('[data-output-kind="skill"]').isDisabled(), true)
      assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
      assert.equal(await page.locator('[data-studio-action="download-output"]').isDisabled(), true)
      await close()
      await page.locator('#undo').click()
      await open()
      assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
      assert.equal(await page.locator('[data-studio-action="download-output"]').isEnabled(), true)
      await close()
      await page.locator('#redo').click()
      await open()
      assert.equal(await page.locator('[data-studio-action="download-output"]').isDisabled(), true)
      await page.locator('[data-output-kind="blueprint"]').check()
      assert.equal(await page.locator('[data-studio-action="download-output"]').isEnabled(), true)
      await close()
      await page.locator('#undo').click()
      await open()
      assert.equal(await page.locator('[data-output-kind="blueprint"]').isChecked(), true)
      return 'Zero stages keeps the exact unavailable procedure visible. Undo restores availability, redo blocks it again, and a deliberate blueprint choice survives later undo.'
    })
    await check('recipe-switch-away-and-back', async () => {
      await fresh()
      await skill()
      const changeRecipe = async value => {
        await page.locator('#project-details').click()
        await page.locator('[data-recipe-select]').selectOption(value)
        await page.locator('#close-inspector').click()
      }
      await changeRecipe('feasibility')
      await open()
      assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
      assert.match(await page.locator('#output-scope').innerText(), /no longer assigned/)
      assert.equal(await page.locator('[data-studio-action="download-output"]').isDisabled(), true)
      await close()
      await changeRecipe('bugfix')
      await open()
      assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
      assert.equal(await page.locator('[data-studio-action="download-output"]').isEnabled(), true)
      return 'Switching away keeps the exact selected procedure but blocks it, and switching back restores it without selecting another procedure.'
    })
    await check('replace-import-and-new-session', async () => {
      await fresh()
      await skill()
      await page.locator('#project-details').click()
      await page.locator('[data-recipe-select]').selectOption('feasibility')
      await page.locator('#close-inspector').click()
      const imported = createRecipe('feasibility')
      imported.project.name = 'Imported study'
      imported.project.purpose = 'Compare ordinary code and a model before selecting an approach.'
      const files = packageProject(imported, compileSelectedOutput(imported, { kind: 'pack' })).files
      const filePath = path.join(output, 'imported-study.zip')
      await fs.writeFile(filePath, zipFiles(files))
      await page.locator('#import-config').click()
      const chooserPromise = page.waitForEvent('filechooser')
      await page.locator('[data-studio-action="choose-project-file"]').click()
      await (await chooserPromise).setFiles(filePath)
      await page.locator('#confirm-dialog').waitFor({ state: 'visible' })
      await page.locator('#confirm-dialog [value="cancel"]').click()
      assert.equal(await page.locator('#project-name').inputValue(), 'Output transitions')
      await open()
      assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
      assert.equal(await page.locator('[data-studio-action="download-output"]').isDisabled(), true)
      await close()
      await page.locator('#new-project').click()
      await page.locator('#confirm-dialog [value="cancel"]').click()
      await open()
      assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
      assert.equal(await page.locator('[data-studio-action="download-output"]').isDisabled(), true)
      await close()
      await page.locator('#import-config').click()
      const nextChooser = page.waitForEvent('filechooser')
      await page.locator('[data-studio-action="choose-project-file"]').click()
      await (await nextChooser).setFiles(filePath)
      await page.locator('#confirm-dialog [value="replace"]').click()
      await page.waitForFunction(() => document.querySelector('#project-name').value === 'Imported study')
      await open()
      assert.equal(await page.locator('[data-output-kind="pack"]').isChecked(), true)
      await close()
      await page.locator('#new-project').click()
      await page.locator('[data-start-recipe="bugfix"]').click()
      await page.locator('#brief-form button[type="submit"]').click()
      await open()
      assert.equal(await page.locator('[data-output-kind="blueprint"]').isChecked(), true)
      return 'Cancel import and new project preserve the unavailable skill and current decisions. Confirmed import adopts its manifest scope. A later new project starts with its own default blueprint.'
    })
    await check('unavailable-output-files-html-control', async () => {
      await fresh()
      await skill()
      await page.locator('#project-details').click()
      await page.locator('[data-recipe-select]').selectOption('feasibility')
      await page.locator('#close-inspector').click()
      await page.locator('#view-nav [data-project-view="artifacts"]').click()
      assert.equal(await page.locator('#export-pack').isDisabled(), true)
      const html = page.locator('#download-atlas')
      const enabled = await html.isEnabled()
      if (enabled) {
        const downloads = []
        page.on('download', download => downloads.push(download.suggestedFilename()))
        await html.click()
        await page.waitForFunction(() => document.querySelector('#toast').textContent.startsWith('Atlas download failed.'))
        report.checks.at(-1).observation = { htmlControlEnabled: enabled, feedback: await page.locator('#toast').innerText(), downloads }
      }
      assert.equal(await html.isDisabled(), true, 'Files view should disable unreadable Atlas export when the chosen procedure is unavailable')
      assert.equal(await page.locator('#export-config').isEnabled(), true)
      await page.locator('#project-details').click()
      await page.locator('[data-recipe-select]').selectOption('bugfix')
      await page.locator('#close-inspector').click()
      await page.waitForFunction(() => !document.querySelector('#download-atlas').disabled)
      const pending = page.waitForEvent('download')
      await html.focus()
      await page.keyboard.press('Enter')
      const downloaded = await pending
      assert.match(downloaded.suggestedFilename(), /\.atlas\.html$/)
      const content = await fs.readFile(await downloaded.path(), 'utf8')
      assert.match(content, /bug-diagnosis/)
      await open()
      await page.locator('.other-downloads summary').focus()
      await page.keyboard.press('Enter')
      await page.keyboard.press('Tab')
      assert.equal(await page.evaluate(() => document.activeElement.dataset.studioAction), 'download-atlas')
      const nextDownload = page.waitForEvent('download')
      await page.keyboard.press('Enter')
      assert.match((await nextDownload).suggestedFilename(), /\.atlas\.html$/)
      return 'Files view disables HTML export alongside ZIP while retaining JSON recovery. Restoring the recipe enables real HTML downloads through keyboard activation in Files and the dialog.'
    })
    await check('keyboard-short-mobile', async () => {
      await fresh({ width: 320, height: 568 })
      await page.locator('#download-project').focus()
      await page.keyboard.press('Enter')
      const focused = () => page.evaluate(() => ({ id: document.activeElement.id, kind: document.activeElement.dataset.outputKind, path: document.activeElement.dataset.selectFile, tag: document.activeElement.tagName }))
      assert.equal((await focused()).tag, 'BUTTON')
      await page.keyboard.press('Tab')
      assert.equal((await focused()).kind, 'blueprint')
      await page.keyboard.press('ArrowRight')
      assert.equal((await focused()).kind, 'skill')
      assert.equal(await page.locator('[data-output-kind="skill"]').isChecked(), true)
      await page.keyboard.press('Tab')
      assert.equal((await focused()).id, 'output-skill')
      const initial = await page.locator('#output-skill').inputValue()
      await page.keyboard.press('ArrowDown')
      assert.equal((await focused()).id, 'output-skill')
      assert.notEqual(await page.locator('#output-skill').inputValue(), initial)
      const chosen = await page.locator('#output-skill').inputValue()
      for (let i = 0; i < 25; i += 1) {
        if (await page.evaluate(() => document.activeElement.matches('.download-reading summary'))) break
        await page.keyboard.press('Tab')
      }
      assert.equal(await page.evaluate(() => document.activeElement.matches('.download-reading summary')), true)
      await page.keyboard.press('Enter')
      await page.keyboard.press('Tab')
      assert.ok((await focused()).path)
      const requested = (await focused()).path
      await page.keyboard.press('Enter')
      assert.equal(await page.locator('#download-dialog').isVisible(), false)
      assert.equal(await page.locator('#preview-path').innerText(), requested)
      assert.equal((await focused()).id, 'artifact-workspace')
      await page.locator('#download-project').focus()
      await page.keyboard.press('Enter')
      assert.equal(await page.locator('#output-skill').inputValue(), chosen)
      await page.keyboard.press('Escape')
      assert.equal((await focused()).id, 'download-project')
      const dimensions = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }))
      assert.ok(dimensions.scrollWidth <= dimensions.width + 1)
      return 'Radio arrows and native select preserve focus. Keyboard activation previews the right file. Escape returns to Download at 320 by 568.'
    })
    await check('practice-edit-with-unavailable-output', async () => {
      await fresh()
      await skill()
      await page.locator('#project-details').click()
      await page.locator('[data-recipe-select]').selectOption('feature-delivery')
      await page.locator('#close-inspector').click()
      const projectJson = async () => {
        await open()
        if (await page.locator('.other-downloads').getAttribute('open') === null) await page.locator('.other-downloads summary').click()
        const pending = page.waitForEvent('download')
        await page.locator('[data-studio-action="download-json"]').click()
        return JSON.parse(await fs.readFile(await (await pending).path(), 'utf8'))
      }
      const before = await projectJson()
      assert.ok(!before.practices.includes('specification-first'))
      const requestPractice = async () => {
        await page.locator('#open-knowledge-map').click()
        const atlas = page.frameLocator('#knowledge-frame')
        await atlas.locator('#mobile-topics').click()
        await atlas.locator('#mobile-search').fill('Requirements investigation')
        await atlas.locator('#mobile-nav [data-topic="requirements-workflow"]').click()
        await atlas.getByRole('button', { name: 'Review for my workflow', exact: true }).click()
        await page.locator('#practice-dialog').waitFor({ state: 'visible' })
        const text = await page.locator('#practice-preview').innerText()
        assert.match(text, /preview (?:is )?unavailable|cannot preview|could not (?:be prepared|compare)|not available/i)
        assert.doesNotMatch(text, /Affected generated files \(0\)/)
        assert.equal(await page.locator('#apply-practice').isEnabled(), true)
        return atlas
      }
      const atlas = await requestPractice()
      await page.setViewportSize({ width: 320, height: 568 })
      const dialogWidth = await page.locator('#practice-dialog').evaluate(element => ({ width: element.clientWidth, scrollWidth: element.scrollWidth }))
      assert.ok(dialogWidth.scrollWidth <= dialogWidth.width + 1)
      await page.locator('#practice-preview .practice-output-note').scrollIntoViewIfNeeded()
      await page.screenshot({ path: path.join(output, 'practice-unavailable-320.png') })
      await page.locator('#apply-practice').focus()
      assert.equal(await page.locator('#apply-practice').evaluate(element => document.activeElement === element), true)
      await page.locator('#practice-dialog .secondary[data-close-dialog="practice-dialog"]').click()
      await atlas.locator('#knowledge-back').click()
      await page.setViewportSize({ width: 1440, height: 1000 })
      assert.deepEqual(await projectJson(), before)
      await requestPractice()
      await page.locator('#apply-practice').click()
      await page.locator('#close-inspector').click()
      await open()
      assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
      assert.equal(await page.locator('[data-studio-action="download-output"]').isDisabled(), true)
      await page.locator('[data-output-kind="blueprint"]').check()
      const pending = page.waitForEvent('download')
      await page.locator('[data-studio-action="download-output"]').click()
      const downloaded = await pending
      const { files } = await unzipTextFiles(new Uint8Array(await fs.readFile(await downloaded.path())))
      const after = JSON.parse(files.find(file => file.path === 'project.json').content)
      assert.deepEqual(after, { ...before, practices: [...before.practices, 'specification-first'] })
      assert.equal(JSON.parse(files.find(file => file.path === 'manifest.json').content).kind, 'blueprint')
      assert.match(files.find(file => file.path === 'WORKFLOW.md').content, /Requirements before implementation/)
      return 'Unavailable output does not block a practice decision. Cancel preserves exact project data. Apply changes only the selected practice, retains the invalid skill choice, and a deliberate blueprint export includes the practice.'
    })
    if (report.pageErrors.length) report.checks.push({ id: 'page-errors', status: 'Fail', error: report.pageErrors.join('\n') })
    assert.ok(report.checks.every(check => check.status === 'Pass'), `Failures recorded in ${output}`)
    console.log(`PASS ${report.checks.length} transition groups. Evidence: ${output}`)
  } finally {
    await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2) + '\n')
    await browser?.close()
    await new Promise(resolve => server.close(resolve))
  }
}

run().catch(error => { console.error(error); process.exitCode = 1 })
