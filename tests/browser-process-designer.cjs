const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require('playwright')

async function run() {
  const root = path.resolve(__dirname, '..')
  const { createAtlasServer } = await import(pathToFileURL(path.join(root, 'tools/serve.mjs')).href)
  const { unzipTextFiles } = await import(pathToFileURL(path.join(root, 'factory/zip.mjs')).href)
  const server = await createAtlasServer({ rootDir: root, getApiKey: () => undefined, transport: () => { throw Error('Unexpected inference request') } })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const output = path.join(root, 'local-knowledge/reviews/process-designer', new Date().toISOString().replace(/[:.]/g, '-'))
  await fs.mkdir(output, { recursive: true })
  const report = { method: 'Browser controls and actual downloaded bytes. No model calls.', limits: 'Functional interaction checks, not a human usability or assistive technology study.', checks: [], errors: [] }
  let browser
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
    page.setDefaultTimeout(10000)
    page.on('pageerror', error => report.errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.address().port}/factory/`)
    await page.locator('[data-start-process]').click()
    const designer = page.locator('#process-designer')
    await designer.locator('[data-pe-start="name"]').fill('Review a proposed result')
    await designer.locator('[data-pe-start="pattern"]').selectOption('bounded-correction')
    await designer.locator('[data-pe-action="create"]').click()
    await designer.locator('[data-pe-bind="steps.0.name"]').fill('Prepare a proposal')
    await designer.locator('[data-pe-bind="steps.0.action"]').fill('Prepare a proposal using the supplied request.')
    await designer.locator('[data-pe-detail="instructions"] summary').click()
    await designer.locator('[data-pe-list="steps.0.instructionIds"][value="requirement-refinement"]').check()
    await designer.locator('[data-pe-select="review"][data-pe-collection="steps"]').first().click()
    await designer.locator('[data-pe-select="result-check"]').click()
    await designer.locator('[data-pe-bind="checks.0.criteria"]').fill('The proposal answers each part of the supplied request.')
    await designer.locator('[data-pe-action="map"]').click()
    assert.equal(await page.evaluate(() => document.activeElement.dataset.peAction), 'map')
    await designer.locator('[data-pe-select="review"][data-pe-collection="steps"]').first().click()
    await designer.locator('[data-pe-select="result-correction"]').click()
    await designer.locator('[data-pe-bind="corrections.0.maxCorrections"]').fill('2')
    await designer.locator('[data-pe-action="review"]').click()
    assert.equal(await designer.locator('[data-pe-action="apply"]').isEnabled(), true)
    await designer.locator('[data-pe-detail="files"] summary').click()
    assert.match(await designer.locator('[data-pe-detail="files"]').innerText(), /EVALUATION\.md/)
    assert.match(await designer.locator('[data-pe-detail="files"]').innerText(), /requirement-refinement/)
    await designer.locator('[data-pe-action="apply"]').click()
    assert.equal(await designer.isVisible(), false)
    assert.equal(await page.locator('[data-select-stage]').count(), 0)
    assert.match(await page.locator('.pe-launcher').innerText(), /Prepare a proposal/)
    report.checks.push('A manual process starts without a software recipe. A selected procedure and check reach the reviewed files before atomic apply.')
    await page.locator('#preview-atlas').click()
    assert.match(await page.locator('#project-content').innerText(), /3 planned steps/)
    assert.doesNotMatch(await page.locator('#project-content').innerText(), /Editing them is the next step|Review 0 selected stages/)
    await page.locator('[data-studio-action="task-brief"]').first().click()
    assert.equal(await page.locator('#brief-context').isVisible(), false)
    await page.locator('#brief-name').fill('Proposal review')
    await page.locator('#brief-purpose').fill('Prepare a reviewed proposal with at most two corrections.')
    await page.locator('#brief-form button[type="submit"]').click()
    await page.locator('#view-nav [data-project-view="workflow"]').click()
    // Undo the brief edit first, then verify the process transaction itself.
    await page.locator('#undo').click()
    await page.locator('#undo').click()
    assert.equal(await page.locator('[data-pe-open]').count(), 0)
    await page.locator('#redo').click()
    assert.match(await page.locator('.pe-launcher').innerText(), /Prepare a proposal/)
    report.checks.push('Undo and Redo restore the entire applied process as one edit.')
    await page.locator('[data-pe-open]').first().click()
    await designer.locator('[data-pe-select="review"][data-pe-collection="steps"]').first().click()
    await designer.locator('[data-pe-route="unavailable"]').selectOption('terminal:complete')
    await designer.locator('[data-pe-action="review"]').click()
    assert.equal(await designer.locator('[data-pe-action="apply"]').isDisabled(), true)
    assert.match(await designer.innerText(), /Needs correction/)
    await designer.locator('[data-pe-action="back"]').click()
    await designer.locator('[data-pe-route="unavailable"]').selectOption('terminal:stopped')
    await designer.locator('[data-pe-bind="steps.1.name"]').fill('A discarded rename')
    await page.keyboard.press('Escape')
    await designer.locator('[data-pe-action="keep-editing"]').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.1.name"]').inputValue(), 'A discarded rename')
    await designer.locator('[data-pe-action="close"]').click()
    await designer.locator('[data-pe-action="discard"]').click()
    assert.doesNotMatch(await page.locator('.pe-launcher').innerText(), /discarded rename/)
    report.checks.push('A failed check cannot complete the process. A rejected draft stays editable, Escape offers keep or discard, and discarded work never reaches the pack.')
    await page.locator('[data-pe-open]').first().click()
    await designer.locator('[data-pe-action="remove-record"]').click()
    assert.match(await designer.innerText(), /entryStepId/)
    await designer.locator('[data-pe-action="cancel-remove"]').click()
    assert.equal(await designer.locator('[data-pe-bind="steps.0.name"]').inputValue(), 'Prepare a proposal')
    report.checks.push('Removing a referenced step shows impacted references and requires an explicit replacement. Cancel preserves the graph.')
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: 900 })
      for (const theme of ['dark', 'light']) {
        await page.evaluate(value => { document.documentElement.dataset.theme = value }, theme)
        const overflow = await designer.evaluate(element => element.scrollWidth > element.clientWidth + 2)
        assert.equal(overflow, false, `${width} ${theme} dialog horizontal overflow`)
        await page.screenshot({ path: path.join(output, `designer-${width}-${theme}.png`) })
      }
    }
    report.checks.push('Designer fits 1440, 390 and 320 pixel widths in both themes. The graph itself remains an explicitly scrollable region.')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await designer.locator('[data-pe-action="close"]').click()
    await page.locator('#download-project').click()
    await page.locator('[data-output-kind="pack"]').check()
    const event = page.waitForEvent('download')
    await page.locator('[data-studio-action="download-output"]').click()
    const downloaded = await event
    const bytes = await fs.readFile(await downloaded.path())
    const { files } = await unzipTextFiles(new Uint8Array(bytes))
    const project = JSON.parse(files.find(file => file.path === 'project.json').content)
    assert.equal(project.workflowModel.processes.length, 1)
    assert.equal(project.workflowModel.processes[0].corrections[0].maxCorrections, 2)
    assert.equal(project.workflowModel.processes[0].transitions.find(route => route.outcome === 'unavailable').to.id, 'stopped')
    assert.match(files.find(file => file.path === '.github/skills/requirement-refinement/references/project.md').content, /Prepare a proposal/)
    assert.match(files.find(file => file.path === 'templates/EVALUATION.md').content, /NOT RUN/)
    assert.match(files.find(file => file.path === 'PROJECT-ATLAS.html').content, /class="pd-scroll"/)
    await fs.writeFile(path.join(output, 'process-pack.zip'), bytes)
    const htmlPath = path.join(output, 'PROJECT-ATLAS.html')
    await fs.writeFile(htmlPath, files.find(file => file.path === 'PROJECT-ATLAS.html').content)
    const reader = await browser.newPage({ viewport: { width: 390, height: 900 } })
    reader.on('pageerror', error => report.errors.push(error.message))
    await reader.goto(pathToFileURL(htmlPath).href)
    await reader.locator('#viewer-nav-toggle').click()
    await reader.locator('[data-view="workflow"]').first().click()
    assert.equal(await reader.locator('.process-design .pd-node').count(), 7)
    assert.equal(await reader.locator('.process-design .pd-scroll').isVisible(), true)
    assert.equal(await reader.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false)
    await reader.screenshot({ path: path.join(output, 'portable-process-390.png') })
    await reader.close()
    await page.locator('[data-close-dialog="download-dialog"]').click()
    await page.locator('#import-file').setInputFiles({ name: 'process-pack.zip', mimeType: 'application/zip', buffer: bytes })
    await page.locator('.pe-launcher').waitFor()
    await page.locator('[data-pe-open]').first().click()
    await designer.locator('[data-pe-select="review"][data-pe-collection="steps"]').first().click()
    await designer.locator('[data-pe-select="result-correction"]').click()
    assert.equal(await designer.locator('[data-pe-bind="corrections.0.maxCorrections"]').inputValue(), '2')
    report.checks.push('Actual ZIP bytes preserve the graph, assigned skill context and NOT RUN evaluation cases. The HTML renders its graph offline at 390 pixels. Reopening through the file input restores editable correction limits.')
    assert.deepEqual(report.errors, [])
    report.passed = true
    console.log(JSON.stringify(report, null, 2))
  } catch (error) { report.failure = error.stack; console.error(error); process.exitCode = 1 }
  finally {
    await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2))
    await browser?.close()
    await new Promise(resolve => server.close(resolve))
    console.log(`Evidence: ${output}`)
  }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
