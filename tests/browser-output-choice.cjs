const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require('playwright')

async function run() {
  const root = path.resolve(__dirname, '..')
  const { createAtlasServer } = await import(pathToFileURL(path.join(root, 'tools/serve.mjs')).href)
  const { unzipTextFiles } = await import(pathToFileURL(path.join(root, 'factory/zip.mjs')).href)
  const server = await createAtlasServer({ rootDir: root, getApiKey: () => undefined, transport: () => { throw new Error('Unexpected provider call') } })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  let browser
  const output = path.join(root, 'local-knowledge/retests/output-choice', new Date().toISOString().replace(/[:.]/g, '-'))
  const report = { method: 'Actual browser controls and downloaded ZIP bytes, isolated local server without credentials or provider calls.', limits: 'Functional checks, not a human comprehension or screen reader study.', checks: [], errors: [] }
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true })
    await fs.mkdir(output, { recursive: true })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
    page.setDefaultTimeout(8000)
    page.on('pageerror', error => report.errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.address().port}/factory/`)
    await page.locator('[data-start-recipe="bugfix"]').click()
    await page.locator('#brief-name').fill('Saved filter repair')
    await page.locator('#brief-purpose').fill('Keep false, zero and empty filter values when saving.')
    await page.locator('#brief-form button[type="submit"]').click()
    const open = async () => { await page.locator('#download-project').click(); await page.locator('#download-dialog').waitFor({ state: 'visible' }) }
    const close = () => page.locator('[data-close-dialog="download-dialog"]').click()
    await open()
    assert.equal(await page.locator('[data-output-kind="blueprint"]').isChecked(), true)
    await page.locator('.download-reading summary').click()
    await page.screenshot({ path: path.join(output, 'download-1440-light.png') })
    report.checks.push('Fresh repair starts with a blueprint, without substituting a diagnosis skill for the repair workflow.')
    await page.locator('[data-output-kind="skill"]').check()
    await page.locator('#output-skill').selectOption('bug-diagnosis')
    assert.match(await page.locator('#output-scope').innerText(), /Bug diagnosis is one procedure.*does not cover the whole/)
    await page.locator('.download-reading summary').click()
    const links = await page.locator('.download-reading [data-select-file]').evaluateAll(elements => elements.map(element => element.dataset.selectFile))
    assert.ok(links.includes('.github/skills/bug-diagnosis/SKILL.md'))
    assert.ok(links.includes('.github/skills/bug-diagnosis/references/project.md'))
    await page.locator('.download-reading [data-select-file=".github/skills/bug-diagnosis/SKILL.md"]').click()
    assert.equal(await page.locator('#download-dialog').isVisible(), false)
    assert.equal(await page.locator('#preview-path').innerText(), '.github/skills/bug-diagnosis/SKILL.md')
    report.checks.push('A focused choice states its limited scope and its reading link opens the actual selected file outside the dialog.')
    await open()
    const downloadPromise = page.waitForEvent('download')
    await page.locator('[data-studio-action="download-output"]').click()
    const download = await downloadPromise
    const bytes = await fs.readFile(await download.path())
    const { files } = await unzipTextFiles(new Uint8Array(bytes))
    const manifest = JSON.parse(files.find(file => file.path === 'manifest.json').content)
    const project = JSON.parse(files.find(file => file.path === 'project.json').content)
    assert.equal(manifest.kind, 'skill')
    assert.equal(manifest.skill, 'bug-diagnosis')
    assert.equal(project.workflow.enabledStages.length, 5)
    assert.ok(!files.some(file => file.path.startsWith('.github/agents/')))
    assert.ok(files.filter(file => file.path.startsWith('.github/skills/')).every(file => file.path.startsWith('.github/skills/bug-diagnosis/')))
    assert.ok(links.every(link => files.some(file => file.path === link)))
    report.checks.push('Downloaded ZIP contains the selected procedure, no agent profiles, and all five original workflow stages in project decisions.')
    await close()
    await page.locator('#view-nav [data-project-view="workflow"]').click()
    for (const stage of ['reproduction', 'diagnosis']) {
      await page.locator(`[data-select-stage="${stage}"]`).first().click()
      await page.locator(`[data-detail="stage-skills-${stage}"] summary`).click()
      await page.locator(`[data-stage-id="${stage}"][data-binding-skill="bug-diagnosis"]`).uncheck()
      await page.locator('#close-inspector').click()
    }
    await open()
    assert.equal(await page.locator('[data-output-kind="skill"]').isChecked(), true)
    assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
    assert.equal(await page.locator('#output-skill').getAttribute('aria-invalid'), 'true')
    assert.match(await page.locator('#output-scope').innerText(), /no longer assigned/)
    assert.equal(await page.locator('[data-studio-action="download-output"]').isDisabled(), true)
    assert.equal(await page.locator('[data-studio-action="download-atlas"]').isDisabled(), true)
    report.checks.push('Removing every assignment blocks ZIP and HTML rather than silently exporting another skill.')
    await close()
    await page.locator('#view-nav [data-project-view="artifacts"]').click()
    assert.equal(await page.locator('#export-pack').isDisabled(), true)
    await page.locator('#view-nav [data-project-view="workflow"]').click()
    await page.locator('[data-select-stage="reproduction"]').first().click()
    const skills = page.locator('[data-detail="stage-skills-reproduction"]')
    if (await skills.getAttribute('open') === null) await skills.locator('summary').click()
    await page.locator('[data-stage-id="reproduction"][data-binding-skill="bug-diagnosis"]').check()
    await page.locator('#close-inspector').click()
    await open()
    assert.equal(await page.locator('#output-skill').inputValue(), 'bug-diagnosis')
    assert.equal(await page.locator('[data-studio-action="download-output"]').isEnabled(), true)
    report.checks.push('The Files view handles unavailable output, and restoring assignment recovers the original skill choice.')
    await page.locator('[data-output-kind="pack"]').check()
    await close()
    await page.locator('#project-details').click()
    await page.locator('[data-field="project.purpose"]').fill('Keep false, zero and empty filter values, including reopened filters.')
    await page.locator('#close-inspector').click()
    await open()
    assert.equal(await page.locator('[data-output-kind="pack"]').isChecked(), true)
    assert.match(await page.locator('.output-recommendation .eyebrow').innerText(), /YOUR CHOICE/)
    report.checks.push('A manually chosen full pack survives a project brief edit.')
    for (const width of [1440, 768, 320]) {
      await page.setViewportSize({ width, height: 1000 })
      for (const theme of ['light', 'dark']) {
        await close()
        const toggle = page.getByRole('switch', { name: 'Dark mode', exact: true })
        if (await page.locator('html').getAttribute('data-theme') !== theme) await toggle.click()
        await open()
        await page.locator('.download-reading summary').click()
        const dimensions = await page.locator('#download-dialog').evaluate(element => ({ width: element.clientWidth, scrollWidth: element.scrollWidth }))
        assert.ok(dimensions.scrollWidth <= dimensions.width + 1, `${width}/${theme} overflow`)
        const radio = page.locator('[data-output-kind="pack"]')
        await radio.focus()
        assert.equal(await radio.evaluate(element => document.activeElement === element), true)
        report.checks.push(`Output selection and expanded reading routes fit at ${width}px in ${theme}, with keyboard focus.`)
      }
    }
    await page.screenshot({ path: path.join(output, 'download-320-dark.png'), fullPage: true })
    assert.deepEqual(report.errors, [])
    console.log(`PASS ${report.checks.length} output selection checks. Evidence: ${output}`)
  } finally {
    await fs.mkdir(output, { recursive: true })
    await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2) + '\n')
    await browser?.close()
    await new Promise(resolve => server.close(resolve))
  }
}

run().catch(error => { console.error(error); process.exitCode = 1 })
